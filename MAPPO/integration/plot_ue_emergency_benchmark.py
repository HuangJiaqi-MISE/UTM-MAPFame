    with plt.rc_context(
        {
            "font.size": 9.5,
            "axes.titlesize": 12,
            "axes.labelsize": 10,
            "xtick.labelsize": 9,
            "ytick.labelsize": 9,
            "figure.facecolor": "white",
            "axes.facecolor": "white",
        }
    ):
        fig, ax = plt.subplots(figsize=(6.8, 4.8))
        service_data = [
            [row["_service_total_ms"] for row in rows if row["recovery_mode"] == mode and row["_service_total_ms"] > 0]
            for mode in modes
        ]
        box = ax.boxplot(
            service_data,
            tick_labels=labels,
            showfliers=False,
            patch_artist=True,
            widths=0.55,
            medianprops={"color": "#333333", "linewidth": 1.2},
        )
        for patch, mode in zip(box["boxes"], modes):
            patch.set_facecolor(mode_colors.get(mode, "#999999"))
            patch.set_alpha(0.5)
            patch.set_edgecolor("#333333")
            patch.set_linewidth(0.9)
        for mode_index, values in enumerate(service_data):
            for value_index, value in enumerate(values):
                jitter = ((value_index % 7) - 3) * 0.025
                ax.scatter(
                    mode_index + 1 + jitter,
                    value,
                    facecolor="#333333",
                    edgecolor="white",
                    linewidth=0.25,
                    alpha=0.48,
                    s=16,
                    zorder=3,
                )
            if values:
                median_value = median(values)
                ax.text(
                    mode_index + 1,
                    max(values) + 0.8,
                    f"median {median_value:.1f} ms",
                    ha="center",
                    va="bottom",
                    fontsize=8.0,
                    color="#333333",
                )
